using TestControllerGrpc.Models;
using TestControllerGrpc.Services;

namespace TestControllerGrpc.Tests.Services;

public class ConsecutiveFailureDetectorTests
{
    private readonly ConsecutiveFailureDetector _detector = new();

    // ???????????????????????????????????????????????????????????????????
    // Priority levels
    // ???????????????????????????????????????????????????????????????????

    [Theory]
    [InlineData(2, "MEDIUM")]
    [InlineData(3, "HIGH")]
    [InlineData(5, "CRITICAL")]
    [InlineData(10, "CRITICAL")]
    public void Alert_Should_HaveCorrectPriority_When_StreakReachesThreshold(int streak, string expected)
    {
        var alert = new ConsecutiveFailureAlert
        {
            TestName = "Test",
            ConsecutiveFailCount = streak,
            Priority = streak >= 5 ? "CRITICAL" : streak >= 3 ? "HIGH" : "MEDIUM"
        };

        Assert.Equal(expected, alert.Priority);
    }

    // ???????????????????????????????????????????????????????????????????
    // ConsecutiveFailureAlert model
    // ???????????????????????????????????????????????????????????????????

    [Fact]
    public void ConsecutiveFailureAlert_Should_HaveDefaultValues_When_Created()
    {
        var alert = new ConsecutiveFailureAlert();

        Assert.Equal("", alert.TestName);
        Assert.Equal("", alert.UseCaseName);
        Assert.Equal("", alert.Priority);
        Assert.Equal("", alert.LastError);
        Assert.Equal(0, alert.ConsecutiveFailCount);
        Assert.Empty(alert.FailedInBuilds);
    }

    [Fact]
    public void ConsecutiveFailureAlert_Should_TrackFailedBuilds_When_BuildsProvided()
    {
        var alert = new ConsecutiveFailureAlert
        {
            TestName = "MyTest",
            ConsecutiveFailCount = 3,
            FailedInBuilds = ["Build3", "Build2", "Build1"],
        };

        Assert.Equal(3, alert.FailedInBuilds.Count);
        Assert.Contains("Build3", alert.FailedInBuilds);
    }
}
