using TestControllerGrpc.Models;

namespace TestControllerGrpc.Tests.Models;

public class PipelineSessionTests
{
    // ?????????????????????????????????????????????????????????????????
    // Defaults
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void PipelineSession_Should_HaveDefaults_When_Created()
    {
        var session = new PipelineSession();

        Assert.Equal(6, session.SessionId.Length);
        Assert.Equal("", session.WatchItemTag);
        Assert.Equal("Running", session.Status);
        Assert.Equal("", session.StatusDetail);
        Assert.Equal(0, session.TotalActions);
        Assert.Equal(0, session.CompletedActions);
        Assert.Equal(0, session.PassedActions);
        Assert.Equal(0, session.FailedActions);
        Assert.Equal(0, session.ProgressPercent);
        Assert.False(session.Cts.IsCancellationRequested);
        Assert.Null(session.ExecutionSession);
        Assert.True(session.StartedUtc <= DateTime.UtcNow);
    }

    [Fact]
    public void SessionId_Should_Be6CharHexString_When_Generated()
    {
        var session = new PipelineSession();
        Assert.Matches("^[0-9a-f]{6}$", session.SessionId);
    }

    [Fact]
    public void DisplayLabel_Should_CombineIdAndTag_When_Read()
    {
        var session = new PipelineSession { WatchItemTag = "MyItem" };
        Assert.Equal($"[{session.SessionId}] MyItem", session.DisplayLabel);
    }

    // ?????????????????????????????????????????????????????????????????
    // RecordPass
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void RecordPass_Should_IncrementPassedAndCompleted_When_Called()
    {
        var session = new PipelineSession { TotalActions = 5 };

        session.RecordPass();

        Assert.Equal(1, session.PassedActions);
        Assert.Equal(1, session.CompletedActions);
        Assert.Equal(0, session.FailedActions);
    }

    [Fact]
    public void RecordPass_Should_UpdateProgressPercent_When_TotalActionsPositive()
    {
        var session = new PipelineSession { TotalActions = 4 };

        session.RecordPass();
        Assert.Equal(25, session.ProgressPercent);

        session.RecordPass();
        Assert.Equal(50, session.ProgressPercent);
    }

    [Fact]
    public void RecordPass_Should_NotDivideByZero_When_TotalActionsIsZero()
    {
        var session = new PipelineSession { TotalActions = 0 };
        session.RecordPass();
        Assert.Equal(0, session.ProgressPercent);
    }

    // ?????????????????????????????????????????????????????????????????
    // RecordFail
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void RecordFail_Should_IncrementFailedAndCompleted_When_Called()
    {
        var session = new PipelineSession { TotalActions = 5 };

        session.RecordFail();

        Assert.Equal(0, session.PassedActions);
        Assert.Equal(1, session.CompletedActions);
        Assert.Equal(1, session.FailedActions);
    }

    [Fact]
    public void RecordFail_Should_UpdateProgressPercent_When_TotalActionsPositive()
    {
        var session = new PipelineSession { TotalActions = 2 };

        session.RecordFail();
        Assert.Equal(50, session.ProgressPercent);
    }

    // ?????????????????????????????????????????????????????????????????
    // Mixed pass/fail
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void MixedPassFail_Should_TrackBothCounters_When_Interleaved()
    {
        var session = new PipelineSession { TotalActions = 4 };

        session.RecordPass();
        session.RecordFail();
        session.RecordPass();
        session.RecordPass();

        Assert.Equal(3, session.PassedActions);
        Assert.Equal(1, session.FailedActions);
        Assert.Equal(4, session.CompletedActions);
        Assert.Equal(100, session.ProgressPercent);
    }

    // ?????????????????????????????????????????????????????????????????
    // Complete
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void Complete_Should_SetStatusSuccess_When_NoFailures()
    {
        var session = new PipelineSession { TotalActions = 2 };
        session.RecordPass();
        session.RecordPass();

        session.Complete();

        Assert.Equal("Success", session.Status);
        Assert.Equal(100, session.ProgressPercent);
    }

    [Fact]
    public void Complete_Should_SetStatusFailed_When_AnyFailure()
    {
        var session = new PipelineSession { TotalActions = 2 };
        session.RecordPass();
        session.RecordFail();

        session.Complete();

        Assert.Equal("Failed", session.Status);
        Assert.Equal(100, session.ProgressPercent);
    }

    [Fact]
    public void Complete_Should_SetStatusSuccess_When_NoActionsRun()
    {
        var session = new PipelineSession();
        session.Complete();

        Assert.Equal("Success", session.Status);
    }

    // ?????????????????????????????????????????????????????????????????
    // Cancel
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void Cancel_Should_SetStatusCancelled_When_Called()
    {
        var session = new PipelineSession();

        session.Cancel();

        Assert.Equal("Cancelled", session.Status);
        Assert.True(session.Cts.IsCancellationRequested);
    }

    [Fact]
    public void Cancel_Should_CancelCtsToken_When_Called()
    {
        var session = new PipelineSession();
        var token = session.Cts.Token;

        session.Cancel();

        Assert.True(token.IsCancellationRequested);
    }

    // ?????????????????????????????????????????????????????????????????
    // Unique sessions
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void SessionId_Should_BeUnique_When_MultipleSessionsCreated()
    {
        var ids = Enumerable.Range(0, 100)
            .Select(_ => new PipelineSession().SessionId)
            .ToHashSet();

        Assert.Equal(100, ids.Count);
    }
}
