    [Fact]
    public void BuildNode_Should_AggregateUseCaseCounts_When_MultipleUseCases()
    {
        var node = new BuildNode
        {
            TotalTests = 80,
            PassedTests = 73,
            FailedTests = 4,
            TimeoutTests = 2,
            NotExecutedTests = 1,
            PassRate = 73.0 / 80.0 * 100,
            UseCases =
            [
                new UseCaseNode { Total = 50, Passed = 45, Failed = 3, Timeout = 2, NotExecuted = 0, TestResults = [] },
                new UseCaseNode { Total = 30, Passed = 28, Failed = 1, Timeout = 0, NotExecuted = 1, TestResults = [] },
            ]
        };

        Assert.Equal(80, node.TotalTests);
        Assert.Equal(73, node.PassedTests);
        Assert.Equal(4, node.FailedTests);
        Assert.Equal(2, node.TimeoutTests);
        Assert.Equal(1, node.NotExecutedTests);
        Assert.Equal(73.0 / 80.0 * 100, node.PassRate, precision: 2);
    }

    [Fact]
    public void BuildNode_Should_ReturnZeroPassRate_When_NoTests()
    {
        var node = new BuildNode { UseCases = [], PassRate = 0 };
        Assert.Equal(0, node.PassRate);
    }

    [Fact]
    public void UseCaseNode_Should_FilterFailedTests_When_FailedTestsAccessed()
    {
        var fail1 = new TestResult { TestName = "Fail1", Outcome = "Failed" };
        var fail2 = new TestResult { TestName = "Fail2", Outcome = "Failed" };

        var uc = new UseCaseNode
        {
            Total = 3, Passed = 1, Failed = 2,
            TestResults =
            [
                new TestResult { TestName = "Pass1", Outcome = "Passed" },
                fail1,
                fail2,
            ],
            FailedTests = [fail1, fail2],
        };

        Assert.Equal(2, uc.FailedTests.Count);
        Assert.All(uc.FailedTests, t => Assert.Equal("Failed", t.Outcome));
    }

    // ???????????????????????????????????????????????????????????????????
    // ExecutionSession model
    // ???????????????????????????????????????????????????????????????????

    [Theory]
    [InlineData(SessionState.Running, "Running")]
    [InlineData(SessionState.Completed, "All")]
    [InlineData(SessionState.PartialFailure, "failed")]
    [InlineData(SessionState.Failed, "failed")]
    public void ExecutionSession_SummaryText_Should_ContainStateInfo_When_StateSet(
        SessionState state, string expectedSubstring)
    {
        var session = new ExecutionSession { State = state };
        session.AddResult(new ActionExecutionResult { Outcome = ActionOutcome.Success });
        session.AddResult(new ActionExecutionResult { Outcome = ActionOutcome.Failed });

        Assert.Contains(expectedSubstring, session.SummaryText, StringComparison.OrdinalIgnoreCase);
    }

