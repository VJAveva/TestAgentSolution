    // BuildNode
    // ?????????????????????????????????????????????????????????????????????

    [Fact]
    public void BuildNode_Should_ComputeTotalDuration_When_UseCasesHaveDuration()
    {
        var node = new BuildNode
        {
            TotalDuration = TimeSpan.FromMinutes(8),
            UseCases =
            [
                new UseCaseNode { Duration = TimeSpan.FromMinutes(5), TestResults = [] },
                new UseCaseNode { Duration = TimeSpan.FromMinutes(3), TestResults = [] },
            ]
        };

        Assert.Equal(TimeSpan.FromMinutes(8), node.TotalDuration);
    }

    [Fact]
    public void BuildNode_Should_CollectAllFailedTests_When_MultipleUseCases()
    {
        var fail1 = new TestResult { TestName = "Fail1", Outcome = "Failed", ErrorMessage = "err1" };
        var fail2 = new TestResult { TestName = "Fail2", Outcome = "Failed", ErrorMessage = "err2" };

        var node = new BuildNode
        {
            UseCases =
            [
                new UseCaseNode
                {
                    TestResults =
                    [
                        new TestResult { TestName = "Pass1", Outcome = "Passed" },
                        fail1,
                    ],
                    FailedTests = [fail1],
                },
                new UseCaseNode
                {
                    TestResults = [fail2],
                    FailedTests = [fail2],
                },
            ],
            AllFailedTests = [fail1, fail2],
        };

        Assert.Equal(2, node.AllFailedTests.Count);
        Assert.Contains(node.AllFailedTests, t => t.TestName == "Fail1");
        Assert.Contains(node.AllFailedTests, t => t.TestName == "Fail2");
    }

    [Fact]
    public void BuildNode_Should_ReturnEmptyFailedList_When_AllPass()
    {
        var node = new BuildNode
        {
            UseCases =
            [
                new UseCaseNode
                {
                    TestResults =
                    [
                        new TestResult { TestName = "Pass1", Outcome = "Passed" },
                    ]
                }
            ],
            AllFailedTests = [],
        };

        Assert.Empty(node.AllFailedTests);
    }

