using System.Text;
using System.Text.Json;

namespace TestController.WebApi.Tests;

/// <summary>
/// Integration tests for /api/watchlist endpoints.
/// </summary>
public class WatchListEndpointsTests : IClassFixture<TestWebAppFactory>
{
    private readonly HttpClient _client;

    public WatchListEndpointsTests(TestWebAppFactory factory)
    {
        _client = factory.CreateClient();
    }

    // ?????????????????????????????????????????????????????????????????
    // GET /api/watchlist
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task GetWatchList_Should_ReturnOk_When_FileExists()
    {
        var response = await _client.GetAsync("/api/watchlist");

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var body = await response.Content.ReadAsStringAsync();
        Assert.Contains("TestBuild", body);
    }

    [Fact]
    public async Task GetWatchList_Should_ReturnJsonWithWatchItems_When_Called()
    {
        var response = await _client.GetAsync("/api/watchlist");
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();

        Assert.True(json.TryGetProperty("watchItems", out var items));
        Assert.Equal(JsonValueKind.Array, items.ValueKind);
        Assert.True(items.GetArrayLength() >= 2);
    }

    // ?????????????????????????????????????????????????????????????????
    // GET /api/watchlist/xml
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task GetWatchListXml_Should_ReturnXml_When_FileExists()
    {
        var response = await _client.GetAsync("/api/watchlist/xml");

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var body = await response.Content.ReadAsStringAsync();
        Assert.Contains("<WatchList>", body);
        Assert.Contains("TestBuild", body);
    }

    // ?????????????????????????????????????????????????????????????????
    // PUT /api/watchlist
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task SaveWatchList_Should_ReturnOk_When_ValidConfig()
    {
        // Read current config first
        var getResponse = await _client.GetAsync("/api/watchlist");
        var json = await getResponse.Content.ReadAsStringAsync();

        // PUT it back
        var content = new StringContent(json, Encoding.UTF8, "application/json");
        var putResponse = await _client.PutAsync("/api/watchlist", content);

        Assert.Equal(HttpStatusCode.OK, putResponse.StatusCode);
    }

    // ?????????????????????????????????????????????????????????????????
    // POST /api/watchlist/import
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task ImportWatchItems_Should_ReturnBadRequest_When_EmptyBody()
    {
        var content = new StringContent("", Encoding.UTF8, "application/xml");
        var response = await _client.PostAsync("/api/watchlist/import", content);

        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
    }

    [Fact]
    public async Task ImportWatchItems_Should_ReturnOk_When_ValidXml()
    {
        var xml = """
            <WatchList>
              <WatchItem Tag="ImportedItem" Path="C:\Imported" Filter="*.txt">
                <Event Type="Renamed" ExecutionType="Sequential">
                  <Action Type="RunCommand" Command="dir" />
                </Event>
              </WatchItem>
            </WatchList>
            """;

        var content = new StringContent(xml, Encoding.UTF8, "application/xml");
        var response = await _client.PostAsync("/api/watchlist/import", content);

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var body = await response.Content.ReadAsStringAsync();
        Assert.Contains("Import complete", body);
    }

    [Fact]
    public async Task ImportWatchItems_Should_ReturnAddedCount_When_NewItemImported()
    {
        var xml = $"""
            <WatchList>
              <WatchItem Tag="UniqueImport_{Guid.NewGuid():N}" Path="C:\New" Filter="*.txt">
                <Event Type="Renamed" ExecutionType="Sequential" />
              </WatchItem>
            </WatchList>
            """;

        var content = new StringContent(xml, Encoding.UTF8, "application/xml");
        var response = await _client.PostAsync("/api/watchlist/import", content);
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();

        Assert.True(json.TryGetProperty("added", out var added));
        Assert.Equal(1, added.GetInt32());
    }

    [Fact]
    public async Task ImportWatchItems_Should_ReturnNoItems_When_XmlHasNoWatchItems()
    {
        var xml = "<WatchList></WatchList>";
        var content = new StringContent(xml, Encoding.UTF8, "application/xml");
        var response = await _client.PostAsync("/api/watchlist/import", content);

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var body = await response.Content.ReadAsStringAsync();
        Assert.Contains("No WatchItems found", body);
    }

    // ?????????????????????????????????????????????????????????????????
    // GET /api/watchlist/export
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task ExportWatchItems_Should_ReturnXml_When_AllItemsExported()
    {
        var response = await _client.GetAsync("/api/watchlist/export");

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var body = await response.Content.ReadAsStringAsync();
        Assert.Contains("<WatchItem", body);
    }

    [Fact]
    public async Task ExportWatchItems_Should_ReturnFilteredXml_When_TagsSpecified()
    {
        var response = await _client.GetAsync("/api/watchlist/export?tags=TestBuild");

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var body = await response.Content.ReadAsStringAsync();
        Assert.Contains("TestBuild", body);
    }

    [Fact]
    public async Task ExportWatchItems_Should_ReturnNotFound_When_TagDoesNotExist()
    {
        var response = await _client.GetAsync("/api/watchlist/export?tags=NonExistent");

        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
    }

    // ?????????????????????????????????????????????????????????????????
    // POST /api/watchlist/refresh
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task RefreshWatchList_Should_ReturnOk_When_FileExists()
    {
        var response = await _client.PostAsync("/api/watchlist/refresh", null);

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();
        Assert.True(json.TryGetProperty("watchItems", out var count));
        Assert.True(count.GetInt32() >= 2);
    }
}
