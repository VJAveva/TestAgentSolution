    // ?????????????????????????????????????????????????????????????????
    // Race condition: trigger with stale lockVersion
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task Trigger_Should_ReturnConflict_When_LockVersionStale()
    {
        // First: get current lockVersion from can-trigger
        var canTriggerResp = await _client.GetAsync("/api/execution/can-trigger/TestBuild");
        var canTriggerJson = await canTriggerResp.Content.ReadFromJsonAsync<JsonElement>();
        var currentVersion = canTriggerJson.GetProperty("lockVersion").GetInt64();

        // Send trigger with a definitely-stale version (version - 1, but only if > 0)
        // If version is 0, this test can't verify the stale check since 0 == current
        if (currentVersion > 0)
        {
            var body = new StringContent(
                JsonSerializer.Serialize(new { lockVersion = currentVersion - 1 }),
                System.Text.Encoding.UTF8, "application/json");

            var response = await _client.PostAsync("/api/execution/trigger/TestBuild", body);

            // Should be 409 Conflict with isStaleState
            if (response.StatusCode == HttpStatusCode.Conflict)
            {
                var json = await response.Content.ReadFromJsonAsync<JsonElement>();
                if (json.TryGetProperty("isStaleState", out var isStale))
                    Assert.True(isStale.GetBoolean());
            }
        }
    }
