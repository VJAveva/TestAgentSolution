using Microsoft.Extensions.Configuration;
using TestController.WebApi.Services;

namespace TestController.WebApi.Tests;

/// <summary>
/// Unit tests for AgentRegistry in-memory service.
/// </summary>
public class AgentRegistryTests
{
    private static AgentRegistry CreateRegistry(params (string Name, string Address)[] agents)
    {
        var dict = new Dictionary<string, string?>();
        for (int i = 0; i < agents.Length; i++)
        {
            dict[$"Agents:{i}:Name"] = agents[i].Name;
            dict[$"Agents:{i}:Address"] = agents[i].Address;
        }

        var config = new ConfigurationBuilder()
            .AddInMemoryCollection(dict)
            .Build();
        return new AgentRegistry(config);
    }

    // ?????????????????????????????????????????????????????????????????
    // Constructor seeding
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void Constructor_Should_SeedAgents_When_ConfigProvided()
    {
        var registry = CreateRegistry(("Agent1", "http://localhost:5200"));

        Assert.True(registry.TryGet("Agent1", out var entry));
        Assert.Equal("http://localhost:5200", entry.Address);
    }

    [Fact]
    public void Constructor_Should_HandleEmpty_When_NoAgentsConfigured()
    {
        var config = new ConfigurationBuilder()
            .AddInMemoryCollection(new Dictionary<string, string?>())
            .Build();
        var registry = new AgentRegistry(config);

        Assert.Empty(registry.GetAll());
    }

    [Fact]
    public void Constructor_Should_SkipInvalid_When_NameOrAddressMissing()
    {
        var config = new ConfigurationBuilder()
            .AddInMemoryCollection(new Dictionary<string, string?>
            {
                ["Agents:0:Name"] = "",
                ["Agents:0:Address"] = "http://localhost:5200",
                ["Agents:1:Name"] = "Valid",
                ["Agents:1:Address"] = "http://localhost:5201",
            })
            .Build();
        var registry = new AgentRegistry(config);

        Assert.Single(registry.GetAll());
        Assert.True(registry.TryGet("Valid", out _));
    }

    // ?????????????????????????????????????????????????????????????????
    // Register
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void Register_Should_AddAgent_When_NewName()
    {
        var registry = CreateRegistry();
        registry.Register("NewAgent", "http://host:1234");

        Assert.True(registry.TryGet("NewAgent", out var entry));
        Assert.Equal("http://host:1234", entry.Address);
    }

    [Fact]
    public void Register_Should_ReplaceAgent_When_NameAlreadyExists()
    {
        var registry = CreateRegistry(("Agent1", "http://old:1111"));
        registry.Register("Agent1", "http://new:2222");

        Assert.True(registry.TryGet("Agent1", out var entry));
        Assert.Equal("http://new:2222", entry.Address);
    }

    // ?????????????????????????????????????????????????????????????????
    // TryGet (case insensitive)
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void TryGet_Should_BeCaseInsensitive_When_LookingUp()
    {
        var registry = CreateRegistry(("MyAgent", "http://localhost:5200"));

        Assert.True(registry.TryGet("myagent", out _));
        Assert.True(registry.TryGet("MYAGENT", out _));
        Assert.True(registry.TryGet("MyAgent", out _));
    }

    [Fact]
    public void TryGet_Should_ReturnFalse_When_AgentNotFound()
    {
        var registry = CreateRegistry();
        Assert.False(registry.TryGet("Missing", out _));
    }

    // ?????????????????????????????????????????????????????????????????
    // Unregister
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void Unregister_Should_RemoveAgent_When_Exists()
    {
        var registry = CreateRegistry(("Agent1", "http://localhost:5200"));

        Assert.True(registry.Unregister("Agent1"));
        Assert.False(registry.TryGet("Agent1", out _));
    }

    [Fact]
    public void Unregister_Should_ReturnFalse_When_AgentNotFound()
    {
        var registry = CreateRegistry();
        Assert.False(registry.Unregister("Missing"));
    }

    // ?????????????????????????????????????????????????????????????????
    // GetAll
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void GetAll_Should_ReturnAllAgents_When_MultipleRegistered()
    {
        var registry = CreateRegistry(
            ("A1", "http://host1:1111"),
            ("A2", "http://host2:2222"));

        var all = registry.GetAll();
        Assert.Equal(2, all.Count);
    }

    // ?????????????????????????????????????????????????????????????????
    // UpdateStatus
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public void UpdateStatus_Should_SetStatus_When_AgentExists()
    {
        var registry = CreateRegistry(("Agent1", "http://localhost:5200"));
        registry.UpdateStatus("Agent1", "Connected", "OK");

        Assert.True(registry.TryGet("Agent1", out var entry));
        Assert.Equal("Connected", entry.Status);
        Assert.Equal("OK", entry.LastStatusDetail);
        Assert.NotNull(entry.LastCheckedUtc);
    }

    [Fact]
    public void UpdateStatus_Should_DoNothing_When_AgentNotFound()
    {
        var registry = CreateRegistry();
        // Should not throw
        registry.UpdateStatus("Missing", "Connected");
    }

    [Fact]
    public void UpdateStatus_Should_OverwritePreviousStatus_When_CalledMultipleTimes()
    {
        var registry = CreateRegistry(("Agent1", "http://localhost:5200"));

        registry.UpdateStatus("Agent1", "Connected");
        registry.UpdateStatus("Agent1", "Unreachable", "Timeout");

        Assert.True(registry.TryGet("Agent1", out var entry));
        Assert.Equal("Unreachable", entry.Status);
        Assert.Equal("Timeout", entry.LastStatusDetail);
    }
}
