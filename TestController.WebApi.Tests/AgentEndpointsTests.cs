using System.Text;
using System.Text.Json;

namespace TestController.WebApi.Tests;

/// <summary>
/// Integration tests for the TestController.WebApi endpoints.
/// Uses WebApplicationFactory to spin up the real pipeline with
/// file-system services pointed at temp directories.
/// </summary>
public class AgentEndpointsTests : IClassFixture<TestWebAppFactory>
{
    private readonly HttpClient _client;

    public AgentEndpointsTests(TestWebAppFactory factory)
    {
        _client = factory.CreateClient();
    }

    // ?????????????????????????????????????????????????????????????????
    // GET /api/agents
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task ListAgents_Should_ReturnOk_When_AgentsSeeded()
    {
        var response = await _client.GetAsync("/api/agents");
        response.EnsureSuccessStatusCode();

        var body = await response.Content.ReadAsStringAsync();
        Assert.Contains("Agent1", body);
    }

    [Fact]
    public async Task ListAgents_Should_ReturnJsonArray_When_Called()
    {
        var response = await _client.GetAsync("/api/agents");
        Assert.Equal(HttpStatusCode.OK, response.StatusCode);

        var json = await response.Content.ReadFromJsonAsync<JsonElement>();
        Assert.Equal(JsonValueKind.Array, json.ValueKind);
    }

    // ?????????????????????????????????????????????????????????????????
    // POST /api/agents/register
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task RegisterAgent_Should_ReturnOk_When_ValidRequest()
    {
        var payload = new { Name = "NewAgent", Address = "http://localhost:9999" };
        var response = await _client.PostAsJsonAsync("/api/agents/register", payload);

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var body = await response.Content.ReadAsStringAsync();
        Assert.Contains("NewAgent", body);
    }

    [Fact]
    public async Task RegisterAgent_Should_ReturnBadRequest_When_NameMissing()
    {
        var payload = new { Name = "", Address = "http://localhost:9999" };
        var response = await _client.PostAsJsonAsync("/api/agents/register", payload);

        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
    }

    [Fact]
    public async Task RegisterAgent_Should_ReturnBadRequest_When_AddressMissing()
    {
        var payload = new { Name = "Agent", Address = "" };
        var response = await _client.PostAsJsonAsync("/api/agents/register", payload);

        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
    }

    // ?????????????????????????????????????????????????????????????????
    // DELETE /api/agents/{name}
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task UnregisterAgent_Should_ReturnNotFound_When_AgentDoesNotExist()
    {
        var response = await _client.DeleteAsync("/api/agents/NonExistentAgent");
        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
    }

    [Fact]
    public async Task UnregisterAgent_Should_ReturnOk_When_AgentExists()
    {
        // Register first
        await _client.PostAsJsonAsync("/api/agents/register",
            new { Name = "ToDelete", Address = "http://localhost:7777" });

        var response = await _client.DeleteAsync("/api/agents/ToDelete");
        Assert.Equal(HttpStatusCode.OK, response.StatusCode);

        var body = await response.Content.ReadAsStringAsync();
        Assert.Contains("ToDelete", body);
    }

    // ?????????????????????????????????????????????????????????????????
    // POST /api/agents/{name}/test
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task TestAgent_Should_ReturnNotFound_When_AgentDoesNotExist()
    {
        var response = await _client.PostAsync("/api/agents/NoSuchAgent/test", null);
        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
    }

    [Fact]
    public async Task TestAgent_Should_ReturnOk_When_AgentUnreachable()
    {
        // Agent1 is seeded but gRPC is not actually running ? returns Unreachable but still 200
        var response = await _client.PostAsync("/api/agents/Agent1/test", null);
        Assert.Equal(HttpStatusCode.OK, response.StatusCode);

        var body = await response.Content.ReadAsStringAsync();
        Assert.Contains("Unreachable", body);
    }

    // ?????????????????????????????????????????????????????????????????
    // POST /api/agents/{name}/diagnose
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task DiagnoseAgent_Should_ReturnNotFound_When_AgentDoesNotExist()
    {
        var response = await _client.PostAsync("/api/agents/NoSuchAgent/diagnose", null);
        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
    }

    // ?????????????????????????????????????????????????????????????????
    // GET /api/agents/{name}/snapshot
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task GetAgentSnapshot_Should_ReturnNotFound_When_AgentDoesNotExist()
    {
        var response = await _client.GetAsync("/api/agents/NoSuchAgent/snapshot");
        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
    }

    // ?????????????????????????????????????????????????????????????????
    // GET /api/agents/{name}/health
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task GetAgentHealth_Should_ReturnNotFound_When_AgentDoesNotExist()
    {
        var response = await _client.GetAsync("/api/agents/NoSuchAgent/health");
        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
    }

    // ?????????????????????????????????????????????????????????????????
    // GET /api/agents/{name}/history
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task GetAgentHistory_Should_ReturnNotFound_When_AgentDoesNotExist()
    {
        var response = await _client.GetAsync("/api/agents/NoSuchAgent/history");
        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
    }

    // ?????????????????????????????????????????????????????????????????
    // GET /api/agents/{name}/audit
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task GetAgentAudit_Should_ReturnNotFound_When_AgentDoesNotExist()
    {
        var response = await _client.GetAsync("/api/agents/NoSuchAgent/audit");
        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
    }
}
