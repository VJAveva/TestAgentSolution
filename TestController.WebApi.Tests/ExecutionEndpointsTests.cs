using System.Text.Json;

namespace TestController.WebApi.Tests;

/// <summary>
/// Integration tests for /api/execution endpoints.
/// </summary>
public class ExecutionEndpointsTests : IClassFixture<TestWebAppFactory>
{
    private readonly HttpClient _client;

    public ExecutionEndpointsTests(TestWebAppFactory factory)
    {
        _client = factory.CreateClient();
    }

    // ?????????????????????????????????????????????????????????????????
    // GET /api/execution/status
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task GetStatus_Should_ReturnOk_When_Called()
    {
        var response = await _client.GetAsync("/api/execution/status");

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();
        Assert.True(json.TryGetProperty("isExecuting", out _));
        Assert.True(json.TryGetProperty("activeCount", out _));
    }

    [Fact]
    public async Task GetStatus_Should_ReturnOkWithExpectedShape_When_Called()
    {
        var response = await _client.GetAsync("/api/execution/status");
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();

        // Verify structure — values depend on test ordering within the shared fixture
        Assert.True(json.TryGetProperty("isExecuting", out var isExec));
        Assert.True(isExec.ValueKind == JsonValueKind.True || isExec.ValueKind == JsonValueKind.False);
        Assert.True(json.TryGetProperty("activeCount", out var count));
        Assert.True(count.GetInt32() >= 0);
    }

    // ?????????????????????????????????????????????????????????????????
    // GET /api/execution/sessions
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task GetSessions_Should_ReturnOk_When_Called()
    {
        var response = await _client.GetAsync("/api/execution/sessions");

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();
        Assert.True(json.TryGetProperty("activeCount", out _));
        Assert.True(json.TryGetProperty("hasActive", out _));
    }

    // ?????????????????????????????????????????????????????????????????
    // POST /api/execution/trigger-all
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task TriggerAll_Should_ReturnOk_When_Called()
    {
        var response = await _client.PostAsync("/api/execution/trigger-all", null);

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();
        Assert.True(json.TryGetProperty("triggered", out var triggered));
        Assert.Equal(JsonValueKind.Array, triggered.ValueKind);
    }

    [Fact]
    public async Task TriggerAll_Should_ReturnTriggeredTags_When_EnabledItemsExist()
    {
        var response = await _client.PostAsync("/api/execution/trigger-all", null);
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();

        var message = json.GetProperty("message").GetString();
        Assert.NotNull(message);
        Assert.Contains("Triggered", message);
    }

    // ?????????????????????????????????????????????????????????????????
    // POST /api/execution/trigger/{tag}
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task TriggerByTag_Should_ReturnNotFound_When_TagDoesNotExist()
    {
        var response = await _client.PostAsync("/api/execution/trigger/NonExistentTag", null);
        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
    }

    [Fact]
    public async Task TriggerByTag_Should_ReturnOk_When_TagExists()
    {
        var response = await _client.PostAsync("/api/execution/trigger/TestBuild", null);

        // Could be OK or Conflict (if already triggered by TriggerAll in same fixture)
        Assert.True(
            response.StatusCode == HttpStatusCode.OK ||
            response.StatusCode == HttpStatusCode.Conflict);
    }

    [Fact]
    public async Task TriggerByTag_Should_ReturnSessionId_When_Triggered()
    {
        // Use DisabledBuild which is less likely to conflict
        var response = await _client.PostAsync("/api/execution/trigger/DisabledBuild", null);

        if (response.StatusCode == HttpStatusCode.OK)
        {
            var json = await response.Content.ReadFromJsonAsync<JsonElement>();
            Assert.True(json.TryGetProperty("sessionId", out var sessionId));
            Assert.False(string.IsNullOrEmpty(sessionId.GetString()));
        }
    }

    // ?????????????????????????????????????????????????????????????????
    // POST /api/execution/trigger-event/{tag}/{eventIndex}
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task TriggerEvent_Should_ReturnNotFound_When_TagDoesNotExist()
    {
        var response = await _client.PostAsync("/api/execution/trigger-event/NoTag/0", null);
        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
    }

    [Fact]
    public async Task TriggerEvent_Should_ReturnBadRequest_When_IndexOutOfRange()
    {
        var response = await _client.PostAsync("/api/execution/trigger-event/TestBuild/99", null);
        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
    }

    [Fact]
    public async Task TriggerEvent_Should_ReturnBadRequest_When_IndexNegative()
    {
        // Negative index — the route constraint is {eventIndex:int} so -1 is valid int
        var response = await _client.PostAsync("/api/execution/trigger-event/TestBuild/-1", null);
        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
    }

    // ?????????????????????????????????????????????????????????????????
    // POST /api/execution/cancel
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task CancelAll_Should_ReturnOk_When_Called()
    {
        var response = await _client.PostAsync("/api/execution/cancel", null);

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var json = await response.Content.ReadFromJsonAsync<JsonElement>();
        Assert.True(json.TryGetProperty("message", out var msg));
        Assert.Contains("Cancel", msg.GetString());
    }

    // ?????????????????????????????????????????????????????????????????
    // POST /api/execution/retry/{sessionId}
    // ?????????????????????????????????????????????????????????????????

    [Fact]
    public async Task RetrySession_Should_ReturnNotFound_When_SessionDoesNotExist()
    {
        var response = await _client.PostAsync("/api/execution/retry/non-existent-session-id", null);
        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
    }
}
