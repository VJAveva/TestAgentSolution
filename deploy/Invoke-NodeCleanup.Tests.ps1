Describe 'Select-BackupSetsToDelete (keep newest N)' {

    $sets = @('20260901-010101', '20260902-010101', '20260903-010101', '20260904-010101', '20260905-010101')

    It 'keeps the newest three and removes the rest' {
        $doomed = Select-BackupSetsToDelete -SetNames $sets -Keep 3
        $doomed.Count | Should Be 2
        ($doomed -contains '20260901-010101') | Should Be $true
        ($doomed -contains '20260902-010101') | Should Be $true
        ($doomed -contains '20260905-010101') | Should Be $false
    }

    It 'removes nothing when the count is at or below the limit' {
        (Select-BackupSetsToDelete -SetNames @('a', 'b') -Keep 3).Count | Should Be 0
        (Select-BackupSetsToDelete -SetNames $sets -Keep 5).Count | Should Be 0
    }

    It 'is a no-op on an empty or null list' {
        (Select-BackupSetsToDelete -SetNames @() -Keep 3).Count | Should Be 0
        (Select-BackupSetsToDelete -SetNames $null -Keep 3).Count | Should Be 0
    }

    It 'is idempotent - a second pass finds nothing left to remove' {
        $doomed = Select-BackupSetsToDelete -SetNames $sets -Keep 3
        $remaining = @($sets | Where-Object { $doomed -notcontains $_ })
        (Select-BackupSetsToDelete -SetNames $remaining -Keep 3).Count | Should Be 0
    }
}

Describe 'Compare-NodeManifest' {

    $manifest = @(
        [pscustomobject]@{ Path = 'TestAgentGrpc.dll'; Sha256 = 'AAA' },
        [pscustomobject]@{ Path = 'Core.dll';          Sha256 = 'BBB' },
        [pscustomobject]@{ Path = 'Gone.dll';          Sha256 = 'CCC' }
    )

    It 'reports Missing, Different and Extra' {
        $actual = @(
            [pscustomobject]@{ Path = 'TestAgentGrpc.dll'; Sha256 = 'AAA' },
            [pscustomobject]@{ Path = 'Core.dll';          Sha256 = 'ZZZ' },
            [pscustomobject]@{ Path = 'Stray.dll';         Sha256 = 'DDD' }
        )
        $r = Compare-NodeManifest -Manifest $manifest -Actual $actual -IgnorePatterns $preserve

        @($r | Where-Object { $_.Status -eq 'Missing'   -and $_.Path -eq 'Gone.dll' }).Count  | Should Be 1
        @($r | Where-Object { $_.Status -eq 'Different' -and $_.Path -eq 'Core.dll' }).Count  | Should Be 1
        @($r | Where-Object { $_.Status -eq 'Extra'     -and $_.Path -eq 'Stray.dll' }).Count | Should Be 1
        $r.Count | Should Be 3
    }

    It 'does not report host state as Extra' {
        # Without the ignore list every node would look wrong: these files legitimately differ.
        $actual = @(
            [pscustomobject]@{ Path = 'TestAgentGrpc.dll'; Sha256 = 'AAA' },
            [pscustomobject]@{ Path = 'Core.dll';          Sha256 = 'BBB' },
            [pscustomobject]@{ Path = 'Gone.dll';          Sha256 = 'CCC' },
            [pscustomobject]@{ Path = 'appsettings.json';  Sha256 = 'EEE' },
            [pscustomobject]@{ Path = 'WatchList.xml';     Sha256 = 'FFF' }
        )
        $r = Compare-NodeManifest -Manifest $manifest -Actual $actual -IgnorePatterns $preserve
        $r.Count | Should Be 0
    }

    It 'is case-insensitive on paths' {
        $actual = @(
            [pscustomobject]@{ Path = 'testagentgrpc.DLL'; Sha256 = 'AAA' },
            [pscustomobject]@{ Path = 'core.dll';          Sha256 = 'BBB' },
            [pscustomobject]@{ Path = 'GONE.dll';          Sha256 = 'CCC' }
        )
        (Compare-NodeManifest -Manifest $manifest -Actual $actual -IgnorePatterns $preserve).Count | Should Be 0
    }

    It 'reports nothing when the node matches exactly' {
        $actual = @(
            [pscustomobject]@{ Path = 'TestAgentGrpc.dll'; Sha256 = 'AAA' },
            [pscustomobject]@{ Path = 'Core.dll';          Sha256 = 'BBB' },
            [pscustomobject]@{ Path = 'Gone.dll';          Sha256 = 'CCC' }
        )
        (Compare-NodeManifest -Manifest $manifest -Actual $actual -IgnorePatterns $preserve).Count | Should Be 0
    }
}

Describe 'Config patch keeps formatting' {

    $json = @"
{
  // two-space indent, blank lines and key order must all survive
  "AgentSettings": {
    "AgentName": "jvgr2",
    "MaxExecutionTimeoutMinutes": 20160
  },

  "WindowsUpdate": {
    "Enabled": true,
    "ScanTimeoutSeconds": 180,
    "ScanPendingUpdates": true
  }
}
"@

    It 'replaces only the targeted value' {
        $out = Set-JsonValuePreservingFormat -Text $json -Path 'WindowsUpdate.ScanTimeoutSeconds' -NewValue 600
        $out.Contains('"ScanTimeoutSeconds": 600') | Should Be $true
        $out.Contains('"ScanTimeoutSeconds": 180') | Should Be $false
    }

    It 'leaves every other byte alone' {
        $out = Set-JsonValuePreservingFormat -Text $json -Path 'WindowsUpdate.ScanTimeoutSeconds' -NewValue 600
        $expected = $json.Replace('"ScanTimeoutSeconds": 180', '"ScanTimeoutSeconds": 600')
        $out | Should Be $expected
    }

    It 'scopes to the right object when a key name repeats' {
        $dup = @"
{
  "A": { "Shared": 1 },
  "B": { "Shared": 2 }
}
"@
        $out = Set-JsonValuePreservingFormat -Text $dup -Path 'B.Shared' -NewValue 99
        $out.Contains('"A": { "Shared": 1 }') | Should Be $true
        $out.Contains('"Shared": 99') | Should Be $true
    }

    It 'handles string and boolean values' {
        $out = Set-JsonValuePreservingFormat -Text $json -Path 'AgentSettings.AgentName' -NewValue 'jvgr7'
        $out.Contains('"AgentName": "jvgr7"') | Should Be $true

        $out2 = Set-JsonValuePreservingFormat -Text $json -Path 'WindowsUpdate.Enabled' -NewValue $false
        $out2.Contains('"Enabled": false') | Should Be $true
    }

    It 'returns null for a key that does not exist' {
        Set-JsonValuePreservingFormat -Text $json -Path 'WindowsUpdate.Nope' -NewValue 1 | Should BeNullOrEmpty
        Set-JsonValuePreservingFormat -Text $json -Path 'Missing.Branch' -NewValue 1 | Should BeNullOrEmpty
    }

    It 'is idempotent - re-applying the same value changes nothing' {
        $once  = Set-JsonValuePreservingFormat -Text $json  -Path 'WindowsUpdate.ScanTimeoutSeconds' -NewValue 600
        $twice = Set-JsonValuePreservingFormat -Text $once  -Path 'WindowsUpdate.ScanTimeoutSeconds' -NewValue 600
        $twice | Should Be $once
    }
}

