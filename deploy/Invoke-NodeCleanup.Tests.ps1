# ---------------------------------------------------------------------------
# Pass 0 and robocopy /XF must agree.
#
# This is the one place a sandbox on disk is unavoidable: the bug was that robocopy's real wildcard
# matching and Pass 0's exact-name matching disagreed, and only robocopy itself can prove the copy
# half. Everything happens under $env:TEMP and is removed in the last It of the block.
# ---------------------------------------------------------------------------
Describe 'Preserve list: Pass 0 agrees with robocopy /MIR' {

    . ([scriptblock]::Create((Get-ScriptFunctionSource -Path $fleetScript -Names @(
        'Test-IsPreserved', 'Get-UnprotectedState', 'Invoke-Robocopy'
    ))))

    # Get-UnprotectedState exempts only the deploy's own backup stamp, which the real script sets here.
    $stamp = '20261003-120000'

    $sandbox = Join-Path $env:TEMP ("fleet-preserve-" + [guid]::NewGuid().ToString('N').Substring(0, 8))
    $src = Join-Path $sandbox 'publish'
    $dst = Join-Path $sandbox 'node'
    New-Item -ItemType Directory -Path $src -Force | Out-Null
    New-Item -ItemType Directory -Path $dst -Force | Out-Null

    Set-Content -Path (Join-Path $src 'TestAgentGrpc.dll') -Value 'payload' -Encoding Ascii
    Set-Content -Path (Join-Path $dst 'TestAgentGrpc.dll') -Value 'payload' -Encoding Ascii

    # Node-only files. The .bak- pair is what the cleanup script used to leave in the install root.
    $backupLeaf = 'commandpolicy.json.bak-20261002-221918'
    Set-Content -Path (Join-Path $dst 'commandpolicy.json') -Value '{}' -Encoding Ascii
    Set-Content -Path (Join-Path $dst $backupLeaf)          -Value '{}' -Encoding Ascii
    Set-Content -Path (Join-Path $dst 'leftover.dll')       -Value 'x'  -Encoding Ascii

    It 'reports a third-party config backup as protected, not at risk' {
        $atRisk = @(Get-UnprotectedState -Remote $dst -Source $src -PreserveFiles $preserve -PreserveFolders @('Logs'))
        @($atRisk | Where-Object { $_.Path -eq $backupLeaf }).Count | Should Be 0
    }

    It 'still reports genuine orphans, so the check has not simply gone quiet' {
        $atRisk = @(Get-UnprotectedState -Remote $dst -Source $src -PreserveFiles $preserve -PreserveFolders @('Logs'))
        @($atRisk | Where-Object { $_.Path -eq 'leftover.dll' }).Count | Should Be 1
    }

    It 'exempts only THIS run stamp, not every .bak- file' {
        # A blanket '*.bak-*' skip used to sit in Get-UnprotectedState, so no backup from any other
        # tool could ever be reported. Proven here with a list that deliberately omits '*.bak-*':
        # protection must come from the preserve list, never from the check looking the other way.
        $noBakList = @($preserve | Where-Object { $_ -ne '*.bak-*' })
        Set-Content -Path (Join-Path $dst "other.json.bak-20250101-000000") -Value '{}' -Encoding Ascii
        Set-Content -Path (Join-Path $dst "appsettings.json.bak-$stamp")    -Value '{}' -Encoding Ascii

        $atRisk = @(Get-UnprotectedState -Remote $dst -Source $src -PreserveFiles $noBakList -PreserveFolders @('Logs'))
        @($atRisk | Where-Object { $_.Path -eq 'other.json.bak-20250101-000000' }).Count | Should Be 1
        @($atRisk | Where-Object { $_.Path -eq "appsettings.json.bak-$stamp" }).Count    | Should Be 0

        Remove-Item (Join-Path $dst "other.json.bak-20250101-000000") -Force
        Remove-Item (Join-Path $dst "appsettings.json.bak-$stamp") -Force
    }

    It 'survives robocopy /MIR with the same list handed to /XF' {
        Invoke-Robocopy -Source $src -Destination $dst -ExcludeFiles $preserve -ExcludeDirs @('Logs') -Mirror | Out-Null
        Test-Path (Join-Path $dst $backupLeaf)          | Should Be $true
        Test-Path (Join-Path $dst 'commandpolicy.json') | Should Be $true
    }

    It 'deleted the file Pass 0 warned about - the two agree in both directions' {
        Test-Path (Join-Path $dst 'leftover.dll') | Should Be $false
    }

    It 'cleans up the sandbox' {
        Remove-Item $sandbox -Recurse -Force -ErrorAction SilentlyContinue
        Test-Path $sandbox | Should Be $false
    }
}
