Describe 'Get-JunkCategory (category-only deletion)' {

    $now = Get-Date '2026-10-03 12:00:00'

    It 'selects a log older than the retention window' {
        Get-JunkCategory -Name 'app_2026-09-01.log' -LastWriteTime $now.AddDays(-30) -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve | Should Be 'OldLogs'
    }

    It 'keeps a log inside the retention window' {
        Get-JunkCategory -Name 'app_2026-10-02.log' -LastWriteTime $now.AddDays(-1) -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve | Should BeNullOrEmpty
    }

    It 'selects a rotated log' {
        Get-JunkCategory -Name 'app.log.3' -LastWriteTime $now.AddDays(-60) -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve | Should Be 'OldLogs'
    }

    It 'selects crash dumps and temp files' {
        Get-JunkCategory -Name 'crash_controller_1.dmp' -LastWriteTime $now.AddDays(-30) -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve -DumpRetentionDays 7 | Should Be 'CrashDumps'
        Get-JunkCategory -Name 'x.tmp' -LastWriteTime $now -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve -DumpRetentionDays 7 | Should Be 'TempFiles'
    }

    It 'keeps a crash dump newer than the dump retention window' {
        # A fresh dump is the evidence for whatever just crashed; deleting it destroys the diagnosis.
        Get-JunkCategory -Name 'crash_controller_1.dmp' -LastWriteTime $now.AddDays(-2) -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve -DumpRetentionDays 7 | Should BeNullOrEmpty
    }

    It 'gates dumps on their own window, not the log window' {
        # 10 days old: past the 7 day dump window, but inside the 14 day log window.
        Get-JunkCategory -Name 'crash.dmp' -LastWriteTime $now.AddDays(-10) -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve -DumpRetentionDays 7 | Should Be 'CrashDumps'
        Get-JunkCategory -Name 'crash.dmp' -LastWriteTime $now.AddDays(-10) -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve -DumpRetentionDays 30 | Should BeNullOrEmpty
    }

    It 'deletes a temp file regardless of age' {
        Get-JunkCategory -Name 'fresh.tmp' -LastWriteTime $now -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve -DumpRetentionDays 7 | Should Be 'TempFiles'
        Get-JunkCategory -Name 'old.tmp' -LastWriteTime $now.AddDays(-900) -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve -DumpRetentionDays 7 | Should Be 'TempFiles'
    }

    It 'never selects audit jsonl, however old' {
        Get-JunkCategory -Name 'audit_2026-01-01.jsonl' -LastWriteTime $now.AddDays(-900) -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve | Should BeNullOrEmpty
    }

    It 'never selects a preserved file, however old' {
        Get-JunkCategory -Name 'appsettings.json' -LastWriteTime $now.AddDays(-900) -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve | Should BeNullOrEmpty
        Get-JunkCategory -Name 'Prepare-Agent.bat' -LastWriteTime $now.AddDays(-900) -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve | Should BeNullOrEmpty
    }

    It 'never selects an ordinary binary' {
        Get-JunkCategory -Name 'TestAgentGrpc.dll' -LastWriteTime $now.AddDays(-900) -Now $now `
            -RetentionDays 14 -PreservePatterns $preserve | Should BeNullOrEmpty
    }
}

