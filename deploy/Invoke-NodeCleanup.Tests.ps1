Describe 'Embedded protected lists match the inventory' {

    # fleet-inventory.json is the single source of truth. The embedded copies are GENERATED by
    # Sync-PreserveList.ps1 because the node has no repo. These tests assert the generated result
    # equals the inventory - not that some literal happens to appear in the file, which would pass
    # even if an entry were listed in an unrelated comment or a stale second array.
    function Get-EmbeddedArray {
        param([string]$Path, [string]$VariableName)
        $ast = [System.Management.Automation.Language.Parser]::ParseFile($Path, [ref]$null, [ref]$null)
        $assign = @($ast.FindAll({
            $args[0] -is [System.Management.Automation.Language.AssignmentStatementAst] -and
            $args[0].Left.Extent.Text -eq $VariableName
        }, $true)) | Select-Object -First 1
        if (-not $assign) { throw "Variable '$VariableName' not found in $Path" }
        $strings = $assign.Right.FindAll({
            $args[0] -is [System.Management.Automation.Language.StringConstantExpressionAst]
        }, $true)
        return @($strings | ForEach-Object { $_.Value })
    }

    It 'Invoke-NodeCleanup.ps1 preserveFiles equals the inventory, in order' {
        if (-not (Test-Path $inventoryPath)) { Set-TestInconclusive -Message 'fleet-inventory.json not present'; return }
        $inv = Get-Content $inventoryPath -Raw | ConvertFrom-Json
        $emb = Get-EmbeddedArray -Path $cleanupScript -VariableName '$script:FallbackPreserveFiles'
        ($emb -join '|') | Should Be ((@($inv.preserveFiles)) -join '|')
    }

    It 'Invoke-NodeCleanup.ps1 preserveFolders equals the inventory, in order' {
        if (-not (Test-Path $inventoryPath)) { Set-TestInconclusive -Message 'fleet-inventory.json not present'; return }
        $inv = Get-Content $inventoryPath -Raw | ConvertFrom-Json
        $emb = Get-EmbeddedArray -Path $cleanupScript -VariableName '$script:FallbackPreserveFolders'
        ($emb -join '|') | Should Be ((@($inv.preserveFolders)) -join '|')
    }

    It 'New-NodeManifest.ps1 preserveFiles equals the inventory, in order' {
        if (-not (Test-Path $inventoryPath)) { Set-TestInconclusive -Message 'fleet-inventory.json not present'; return }
        $inv = Get-Content $inventoryPath -Raw | ConvertFrom-Json
        $emb = Get-EmbeddedArray -Path $manifestScript -VariableName '$fallbackPreserveFiles'
        ($emb -join '|') | Should Be ((@($inv.preserveFiles)) -join '|')
    }

    It 'regenerating from the inventory is a no-op (Sync-PreserveList.ps1 -Check)' {
        $sync = Join-Path $here 'Sync-PreserveList.ps1'
        if (-not (Test-Path $sync)) { Set-TestInconclusive -Message 'Sync-PreserveList.ps1 not present'; return }
        & powershell -NoProfile -ExecutionPolicy Bypass -File $sync -Check | Out-Null
        $LASTEXITCODE | Should Be 0
    }

    It 'defines Test-IsPreserved identically in both scripts' {
        # Two copies exist because the node has no repo. If the bodies ever diverge, the cleanup and
        # the deploy can protect different files - which is the whole defect this block guards.
        # Get-ScriptFunctionSource throws when the function is absent, so reaching the compare is itself
        # an assertion that both scripts still define it.
        $a = (Get-ScriptFunctionSource -Path $cleanupScript -Names @('Test-IsPreserved')) -replace '\s+', ' '
        $b = (Get-ScriptFunctionSource -Path $fleetScript   -Names @('Test-IsPreserved')) -replace '\s+', ' '
        $a.Trim() | Should Be $b.Trim()
    }
}

Describe 'Get-TotalBytes' {

    It 'returns 0 for an empty collection instead of throwing' {
        # Measure-Object -Sum raises "Argument types do not match" on an empty set, and the script
        # runs with $ErrorActionPreference = Stop, so this once killed report generation on a node
        # that happened to be clean.
        Get-TotalBytes -Items @() | Should Be 0
        Get-TotalBytes -Items (New-Object System.Collections.Generic.List[object]) | Should Be 0
        Get-TotalBytes -Items $null | Should Be 0
    }

    It 'sums the named property' {
        $items = @(
            [pscustomobject]@{ Bytes = 100 },
            [pscustomobject]@{ Bytes = 250 }
        )
        Get-TotalBytes -Items $items | Should Be 350
    }

    It 'sums an alternative property' {
        $items = @(
            [pscustomobject]@{ Length = 10 },
            [pscustomobject]@{ Length = 32 }
        )
        Get-TotalBytes -Items $items -Property 'Length' | Should Be 42
    }
}

