<#
    Pester 3.4 (the version that ships with Windows PowerShell 5.1) - "Should Be", not "Should -Be".

    The scripts under test run top to bottom, so dot-sourcing them would execute a cleanup. Instead
    the pure helpers are lifted out with the PowerShell AST and defined into this session.

    No real node is touched. The only test that writes to disk is the robocopy agreement block at the
    bottom, which builds and deletes its own sandbox under $env:TEMP.

    Run:  Invoke-Pester -Path .\deploy\Invoke-NodeCleanup.Tests.ps1
#>

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$cleanupScript  = Join-Path $here 'Invoke-NodeCleanup.ps1'
$manifestScript = Join-Path $here 'New-NodeManifest.ps1'
$fleetScript    = Join-Path $here 'Invoke-FleetDeployment.ps1'
$inventoryPath  = Join-Path $here 'fleet-inventory.json'

function Get-ScriptFunctionSource {
    param([string]$Path, [string[]]$Names)

    $ast = [System.Management.Automation.Language.Parser]::ParseFile($Path, [ref]$null, [ref]$null)
    $fns = $ast.FindAll({ $args[0] -is [System.Management.Automation.Language.FunctionDefinitionAst] }, $true)

    $sb = New-Object System.Text.StringBuilder
    foreach ($n in $Names) {
        $f = @($fns | Where-Object { $_.Name -eq $n })
        if ($f.Count -eq 0) { throw "Function '$n' not found in $Path" }
        [void]$sb.AppendLine($f[0].Extent.Text)
    }
    return $sb.ToString()
}

# Dot-source at SCRIPT scope. Invoke-Expression inside the helper would define the functions in
# that helper's scope, and every test would then fail with CommandNotFoundException.
. ([scriptblock]::Create((Get-ScriptFunctionSource -Path $cleanupScript -Names @(
